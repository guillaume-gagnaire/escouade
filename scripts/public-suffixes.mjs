#!/usr/bin/env node
// schemas/public-suffixes.mjs, the ICANN section of the public suffix list (audit SEC-09, ESC-596), from a copy of
// https://publicsuffix.org/list/public_suffix_list.dat read on disk: `node scripts/public-suffixes.mjs <list.dat>`.
// The manifest's reader of the store and of the SDK (schemas/plugin-manifest.mjs) refuses with it a host of
// `permissions.network` that is a public suffix; the core's does the same with the crate `psl`. Nothing is fetched here:
// download the list by hand, then run this again (its rules are written ASCII, as a URL's host is).
import { readFileSync, writeFileSync } from 'node:fs';
import { domainToASCII } from 'node:url';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const [source] = process.argv.slice(2);
if (!source) {
  console.error('usage: node scripts/public-suffixes.mjs <public_suffix_list.dat>');
  process.exit(2);
}
const text = readFileSync(source, 'utf8');
const begin = text.indexOf('// ===BEGIN ICANN DOMAINS===');
const end = text.indexOf('// ===END ICANN DOMAINS===');
if (begin < 0 || end < begin) {
  console.error('no ICANN section in this file');
  process.exit(1);
}
const rules = new Set();
for (const raw of text.slice(begin, end).split('\n')) {
  const line = raw.trim();
  if (!line || line.startsWith('//')) continue;
  const [prefix, rest] = line.startsWith('!') ? ['!', line.slice(1)] : line.startsWith('*.') ? ['*.', line.slice(2)] : ['', line];
  const ascii = domainToASCII(rest);
  if (!ascii) continue;
  rules.add(prefix + ascii);
}
const sorted = [...rules].sort();
const out = `// Generated by scripts/public-suffixes.mjs from the public suffix list (https://publicsuffix.org, MPL 2.0), its ICANN
// section alone: do not edit, run it again. ${sorted.length} rules, \`*.\` for a wildcard and \`!\` for an exception.

/** The rules of the ICANN section, ASCII, lower case. */
export const ICANN_RULES = new Set(${JSON.stringify(sorted.join(' '))}.split(' '));

/**
 * Whether \`domain\` (ASCII, lower case, no trailing dot) is a public suffix of the ICANN section: \`com\`, \`co.uk\`,
 * \`anything.kawasaki.jp\` (by \`*.kawasaki.jp\`), not \`city.kawasaki.jp\` (by \`!city.kawasaki.jp\`).
 */
export function isPublicSuffix(domain) {
  if (!domain || ICANN_RULES.has(\`!\${domain}\`)) return false;
  if (ICANN_RULES.has(domain)) return true;
  const dot = domain.indexOf('.');
  return dot > 0 && ICANN_RULES.has(\`*.\${domain.slice(dot + 1)}\`);
}
`;
const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(resolve(here, '..', 'schemas', 'public-suffixes.mjs'), out);
console.log(`schemas/public-suffixes.mjs: ${sorted.length} rules`);
