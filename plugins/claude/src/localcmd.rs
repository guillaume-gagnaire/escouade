//! What Claude Code writes of a local command, run by itself and not by the model (ESC-154):
//! `/compact`, `/model opus`, `/cost`… (`<command-name>`, `<local-command-stdout>`, `-stderr>`,
//! after a `<local-command-caveat>`), and the `!` mode's shell commands (`<bash-input>`, then
//! `<bash-stdout>…</bash-stdout><bash-stderr>…</bash-stderr>`). Read the same way whatever told
//! it (the stream, a replayed message, the transcript of the terminal view), its text a string or
//! text blocks. `src/lib/localcmd.ts` reads them the same way in conversations saved before.

use crate::words::strip_ansi;

#[derive(Debug, PartialEq)]
pub enum Part {
    /// The command as it was typed: `/model opus`, `! ls`.
    Typed(String),
    /// What it printed, its lines kept, without its ANSI codes.
    Output(String),
    /// What it printed as an error.
    Error(String),
}

/// What `text` tells of a local command: `None` when it is no local command's, else its parts,
/// none for what is not shown (the caveat, an output with nothing in it).
pub fn parse(text: &str) -> Option<Vec<Part>> {
    if text.trim_start().starts_with("<local-command-caveat>") {
        return Some(Vec::new());
    }
    if let Some(name) = tag(text, "command-name") {
        let args = tag(text, "command-args").unwrap_or("").trim();
        let name = name.trim();
        let typed = if args.is_empty() {
            name.to_string()
        } else {
            format!("{name} {args}")
        };
        return Some(vec![Part::Typed(typed)]);
    }
    if let Some(input) = tag(text, "bash-input") {
        return Some(vec![Part::Typed(format!("! {}", input.trim()))]);
    }
    let mut parts = Vec::new();
    let mut found = false;
    for (name, error) in [
        ("local-command-stdout", false),
        ("bash-stdout", false),
        ("local-command-stderr", true),
        ("bash-stderr", true),
    ] {
        let Some(body) = tag(text, name) else {
            continue;
        };
        found = true;
        let body = output(body);
        if body.is_empty() {
            continue;
        }
        parts.push(if error {
            Part::Error(body)
        } else {
            Part::Output(body)
        });
    }
    found.then_some(parts)
}

/// What is between `<name>` and `</name>` in `text` (to its end when it is not closed).
fn tag<'a>(text: &'a str, name: &str) -> Option<&'a str> {
    let (_, rest) = text.split_once(&format!("<{name}>"))?;
    Some(rest.split(&format!("</{name}>")).next().unwrap_or(rest))
}

/// An output as shown: its ANSI codes removed (the conversation is no terminal: colors and faint
/// text would be codes left as they are), its lines and their indent kept (the table of
/// `/context`), without the blank lines and spaces around it.
fn output(body: &str) -> String {
    let text = strip_ansi(&body.replace("\r\n", "\n"));
    let lines: Vec<&str> = text.lines().map(str::trim_end).collect();
    let first = lines.iter().position(|l| !l.is_empty());
    let last = lines.iter().rposition(|l| !l.is_empty());
    match (first, last) {
        (Some(a), Some(b)) => lines[a..=b].join("\n"),
        _ => String::new(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_command_reads_as_typed_with_its_arguments() {
        assert_eq!(
            parse("<command-name>/compact</command-name>\n            <command-message>compact</command-message>\n            <command-args></command-args>"),
            Some(vec![Part::Typed("/compact".into())])
        );
        assert_eq!(
            parse("<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args>opus</command-args>"),
            Some(vec![Part::Typed("/model opus".into())])
        );
        assert_eq!(
            parse("<bash-input>git status</bash-input>"),
            Some(vec![Part::Typed("! git status".into())])
        );
    }

    #[test]
    fn the_caveat_and_an_empty_output_show_nothing() {
        assert_eq!(
            parse("<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>"),
            Some(vec![])
        );
        assert_eq!(
            parse("<local-command-stdout></local-command-stdout>"),
            Some(vec![])
        );
        assert_eq!(
            parse("<bash-stdout></bash-stdout><bash-stderr></bash-stderr>"),
            Some(vec![])
        );
    }

    #[test]
    fn an_output_keeps_its_lines_and_loses_its_ansi_codes() {
        let text = "<local-command-stdout>\r\n \u{1b}[1mContext Usage\u{1b}[22m\r\n \u{1b}[38;5;246m⛁ ⛁\u{1b}[39m   claude-opus · 12k/200k tokens  \r\n\r\n   System prompt: 3k\r\n</local-command-stdout>";
        assert_eq!(
            parse(text),
            Some(vec![Part::Output(
                " Context Usage\n ⛁ ⛁   claude-opus · 12k/200k tokens\n\n   System prompt: 3k"
                    .into()
            )])
        );
        assert_eq!(
            parse("<local-command-stdout>\u{1b}]8;;https://x.dev\u{7}x.dev\u{1b}]8;;\u{1b}\\ ok</local-command-stdout>"),
            Some(vec![Part::Output("x.dev ok".into())])
        );
        assert_eq!(
            parse("<local-command-stdout>Compacted </local-command-stdout>"),
            Some(vec![Part::Output("Compacted".into())])
        );
    }

    #[test]
    fn an_error_output_is_an_error_and_the_shells_two_outputs_are_both_read() {
        assert_eq!(
            parse("<local-command-stderr>Error during compaction</local-command-stderr>"),
            Some(vec![Part::Error("Error during compaction".into())])
        );
        assert_eq!(
            parse("<bash-stdout>a\nb</bash-stdout><bash-stderr>warning: x</bash-stderr>"),
            Some(vec![
                Part::Output("a\nb".into()),
                Part::Error("warning: x".into())
            ])
        );
    }

    #[test]
    fn any_other_text_is_no_local_command() {
        assert_eq!(parse("Bonjour"), None);
        assert_eq!(parse("<task-notification>x</task-notification>"), None);
        assert_eq!(parse("/compact"), None);
    }
}
