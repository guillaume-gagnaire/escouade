/**
 * MO-3 and MO-4: the mobile app's native side under Android. The Rust (crates/escouade-mobile) through the Kotlin
 * bindings of UniFFI (generated by scripts/mobile-android.sh into src/main/java/uniffi, loaded by JNA from
 * libescouade_mobile.so); each space's keys and token in the Keystore (SR1-15, ESC-570): an AES key of the
 * AndroidKeyStore, never exported, seals what the space keeps in the app's private preferences (the app is never backed
 * up: allowBackup false, data_extraction_rules). The JavaScript passes a space's id, never a key.
 * The API is src/definitions.ts; a failure rejects with the crate's error as the code (`Forged`, `BadKey`…).
 */
@CapacitorPlugin(name = "EscouadeMobile")
class EscouadeMobilePlugin : Plugin() {
    /** A space's way: its tunnel, or a proxy to its address. */
    private class Way(val tunnel: MobileTunnel?, val direct: MobileDirect?) {
        fun status(): MobileTunnelStatus = tunnel?.status() ?: direct!!.status()
        fun stop() {
            tunnel?.let { it.stop(); it.destroy() }
            direct?.let { it.stop(); it.destroy() }
        }
    }

    /** One way per space. */
    private val ways = ConcurrentHashMap<String, Way>()

    /** The pairings under way, in memory alone: what was read, and the phone's private half. */
    private val pending = ConcurrentHashMap<String, JSONObject>()
    private val halves = ConcurrentHashMap<String, String>()

    private fun reject(call: PluginCall, e: MobileException) = call.reject(e.message ?: e.toString(), e.javaClass.simpleName)

    private fun status(space: String, s: MobileTunnelStatus): JSObject {
        val o = JSObject()
            .put("space", space)
            .put("state", s.state.name.lowercase())
            .put("proxyUrl", s.proxyUrl)
            .put("websocketUrl", s.websocketUrl)
            .put("txBytes", s.txBytes.toLong())
            .put("rxBytes", s.rxBytes.toLong())
            .put("connections", s.connections.toLong())
        s.lastHandshakeSecs?.let { o.put("lastHandshakeSecs", it.toLong()) }
        s.error?.let { o.put("error", it) }
        return o
    }

    private fun stop(space: String) {
        ways.remove(space)?.stop()
    }

    // ---------- the Keystore ----------

    private val alias = "escouade-spaces"
    private val prefs by lazy { context.getSharedPreferences("escouade-spaces", Context.MODE_PRIVATE) }

    private fun aesKey(): SecretKey {
        val store = KeyStore.getInstance("AndroidKeyStore").apply { load(null) }
        (store.getKey(alias, null) as? SecretKey)?.let { return it }
        val gen = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, "AndroidKeyStore")
        gen.init(
            KeyGenParameterSpec.Builder(alias, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT)
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                .build(),
        )
        return gen.generateKey()
    }

    private fun keep(space: String, kept: JSONObject) {
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(Cipher.ENCRYPT_MODE, aesKey())
        val sealed = cipher.iv + cipher.doFinal(kept.toString().toByteArray(Charsets.UTF_8))
        prefs.edit().putString(space, Base64.encodeToString(sealed, Base64.NO_WRAP)).apply()
    }

    private fun kept(space: String): JSONObject? {
        val text = prefs.getString(space, null) ?: return null
        return try {
            val sealed = Base64.decode(text, Base64.NO_WRAP)
            val cipher = Cipher.getInstance("AES/GCM/NoPadding")
            cipher.init(Cipher.DECRYPT_MODE, aesKey(), GCMParameterSpec(128, sealed, 0, 12))
            JSONObject(String(cipher.doFinal(sealed, 12, sealed.size - 12), Charsets.UTF_8))
        } catch (e: Exception) {
            null
        }
    }

    // ---------- the lock ----------

    private fun screenLock(): Boolean = (context.getSystemService(Context.KEYGUARD_SERVICE) as KeyguardManager).isDeviceSecure

    @PluginMethod
    fun lockState(call: PluginCall) {
        val strong = BiometricManager.from(context).canAuthenticate(BiometricManager.Authenticators.BIOMETRIC_STRONG) ==
            BiometricManager.BIOMETRIC_SUCCESS
        val pm = context.packageManager
        val biometry = when {
            !strong -> "none"
            pm.hasSystemFeature(PackageManager.FEATURE_FINGERPRINT) -> "fingerprint"
            Build.VERSION.SDK_INT >= 29 && pm.hasSystemFeature(PackageManager.FEATURE_FACE) -> "face"
            else -> "fingerprint"
        }
        call.resolve(JSObject().put("screenLock", screenLock()).put("biometry", biometry))
    }

    @PluginMethod
    fun unlock(call: PluginCall) {
        val reason = call.getString("reason") ?: ""
        if (!screenLock()) return call.reject("no screen lock", "NoLock")
        val activity = activity as? FragmentActivity ?: return call.reject("no activity", "Cancelled")
        activity.runOnUiThread {
            val prompt = BiometricPrompt(
                activity,
                ContextCompat.getMainExecutor(context),
                object : BiometricPrompt.AuthenticationCallback() {
                    override fun onAuthenticationSucceeded(result: BiometricPrompt.AuthenticationResult) = call.resolve()
                    override fun onAuthenticationError(code: Int, message: CharSequence) =
                        if (code == BiometricPrompt.ERROR_NO_DEVICE_CREDENTIAL) call.reject("no screen lock", "NoLock")
                        else call.reject(message.toString(), "Cancelled")
                },
            )
            val info = BiometricPrompt.PromptInfo.Builder().setTitle("Escouade").setSubtitle(reason)
            if (Build.VERSION.SDK_INT >= 30) {
                info.setAllowedAuthenticators(
                    BiometricManager.Authenticators.BIOMETRIC_STRONG or BiometricManager.Authenticators.DEVICE_CREDENTIAL,
                )
            } else {
                @Suppress("DEPRECATION")
                info.setDeviceCredentialAllowed(true)
            }
            prompt.authenticate(info.build())
        }
    }

    // ---------- the pairing ----------

    @PluginMethod
    fun readPairing(call: PluginCall) {
        val space = call.getString("space") ?: return call.reject("space is required", "BadConfig")
        val qr = call.getString("qr")
        val api = call.getString("api")
        val found = JSObject()
        val kept = JSONObject()
        if (qr != null) {
            val read = try {
                JSONObject(qr)
            } catch (e: Exception) {
                return call.reject("not a QR code of Escouade", "BadPairing")
            }
            if (read.optString("escouade") != "pair/1") return call.reject("not a QR code of Escouade's pairing", "BadPairing")
            val tunnel = read.optJSONObject("tunnel") ?: return call.reject("no tunnel in the QR code", "BadPairing")
            kept.putOpt("kind", "tunnel")
            for (k in listOf("privateKey", "peerPublicKey", "endpoint", "address", "api")) kept.putOpt(k, tunnel.optString(k))
            found.put("kind", "tunnel")
                .put("name", read.optString("name"))
                .put("here", read.optBoolean("here"))
                .put("version", read.optString("version"))
                .put("code", read.optString("code"))
                .put("expiresAt", read.optLong("expiresAt"))
                .put("endpoint", tunnel.optString("endpoint"))
        } else if (api != null) {
            kept.putOpt("kind", "direct").putOpt("api", api.trim())
            found.put("kind", "direct").put("endpoint", api.trim())
        } else {
            return call.reject("a QR code or an address", "BadConfig")
        }
        stop(space)
        halves.remove(space)
        pending[space] = kept
        call.resolve(found)
    }

    @PluginMethod
    fun pairingKey(call: PluginCall) {
        val space = call.getString("space") ?: return call.reject("space is required", "BadConfig")
        // No pairing without a screen lock (M3, docs/MOBILE.md § 3.9).
        if (!screenLock()) return call.reject("no screen lock", "NoLock")
        if (!pending.containsKey(space)) return call.reject("no pairing under way", "NoSpace")
        val key = newPairingKey()
        halves[space] = key.privateKey
        call.resolve(JSObject().put("publicKey", key.publicKey))
    }

    @PluginMethod
    fun finishPairing(call: PluginCall) {
        val space = call.getString("space") ?: return call.reject("space is required", "BadConfig")
        val coreKey = call.getString("coreKey") ?: ""
        val kept = pending[space] ?: return call.reject("no pairing under way", "NoSpace")
        val half = halves[space] ?: return call.reject("no pairing under way", "NoSpace")
        try {
            val p = rustFinishPairing(half, coreKey)
            kept.putOpt("token", p.deviceToken).putOpt("pairingKey", p.pairingKey)
            keep(space, kept)
            pending.remove(space)
            halves.remove(space)
            stop(space)
            call.resolve()
        } catch (e: MobileException) {
            reject(call, e)
        }
    }

    @PluginMethod
    fun forgetSpace(call: PluginCall) {
        val space = call.getString("space") ?: return call.reject("space is required", "BadConfig")
        stop(space)
        pending.remove(space)
        halves.remove(space)
        prefs.edit().remove(space).apply()
        call.resolve()
    }

    // ---------- the way to a space ----------

    @PluginMethod
    fun startTunnel(call: PluginCall) {
        val space = call.getString("space") ?: return call.reject("space is required", "BadConfig")
        val kept = kept(space) ?: pending[space] ?: return call.reject("nothing kept of this space", "NoSpace")
        val token = kept.optString("token").takeIf { it.isNotEmpty() }
        // Capacitor calls a plugin off the main thread: resolving the endpoint (DNS) may wait here.
        try {
            stop(space)
            val way = if (kept.optString("kind") == "direct") {
                Way(null, MobileDirect.start(kept.optString("api"), token))
            } else {
                Way(
                    MobileTunnel.start(
                        MobileTunnelConfig(
                            privateKey = kept.optString("privateKey"),
                            peerPublicKey = kept.optString("peerPublicKey"),
                            presharedKey = null,
                            endpoint = kept.optString("endpoint"),
                            address = kept.optString("address"),
                            api = kept.optString("api"),
                            keepaliveSecs = null,
                            deviceToken = token,
                        ),
                    ),
                    null,
                )
            }
            ways[space] = way
            call.resolve(status(space, way.status()))
        } catch (e: MobileException) {
            reject(call, e)
        }
    }

    @PluginMethod
    fun tunnelStatus(call: PluginCall) {
        val space = call.getString("space") ?: return call.reject("space is required", "BadConfig")
        val way = ways[space] ?: return call.reject("no tunnel for this space", "NoTunnel")
        call.resolve(status(space, way.status()))
    }

    @PluginMethod
    fun stopTunnel(call: PluginCall) {
        val space = call.getString("space") ?: return call.reject("space is required", "BadConfig")
        stop(space)
        call.resolve()
    }

    @PluginMethod
    fun openNotification(call: PluginCall) {
        val space = call.getString("space") ?: return call.reject("space is required", "BadConfig")
        val key = kept(space)?.optString("pairingKey") ?: return call.reject("nothing kept of this space", "NoSpace")
        try {
            val n = rustOpenNotification(
                key,
                call.getString("sealed") ?: "",
                call.getString("guardState") ?: "",
            )
            val o = JSObject()
                .put("seq", n.seq.toLong())
                .put("at", n.at.toLong())
                .put("kind", n.kind)
                .put("title", n.title)
                .put("body", n.body)
                .put("guardState", n.guardState)
            n.target?.let { o.put("target", it) }
            call.resolve(o)
        } catch (e: MobileException) {
            reject(call, e)
        }
    }

    @PluginMethod
    fun version(call: PluginCall) = call.resolve(JSObject().put("version", mobileVersion()))

    override fun handleOnDestroy() {
        ways.keys.toList().forEach(::stop)
        super.handleOnDestroy()
    }
}
