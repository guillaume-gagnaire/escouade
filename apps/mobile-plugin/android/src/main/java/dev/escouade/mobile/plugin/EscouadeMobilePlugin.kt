package dev.escouade.mobile.plugin

import com.getcapacitor.JSObject
import com.getcapacitor.Plugin
import com.getcapacitor.PluginCall
import com.getcapacitor.PluginMethod
import com.getcapacitor.annotation.CapacitorPlugin
import java.util.concurrent.ConcurrentHashMap
import uniffi.escouade_mobile.MobileException
import uniffi.escouade_mobile.MobileTunnel
import uniffi.escouade_mobile.MobileTunnelConfig
import uniffi.escouade_mobile.MobileTunnelStatus
import uniffi.escouade_mobile.mobileVersion
import uniffi.escouade_mobile.openNotification as rustOpenNotification

/**
 * MO-3: the mobile app's Rust (crates/escouade-mobile) under Android, through the Kotlin bindings of UniFFI
 * (generated by scripts/mobile-android.sh into src/main/java/uniffi, loaded by JNA from libescouade_mobile.so).
 * The API is src/definitions.ts; a failure rejects with the crate's error as the code (`Forged`, `BadKey`…).
 */
@CapacitorPlugin(name = "EscouadeMobile")
class EscouadeMobilePlugin : Plugin() {
    /** One tunnel per space. */
    private val tunnels = ConcurrentHashMap<String, MobileTunnel>()

    private fun reject(call: PluginCall, e: MobileException) = call.reject(e.message ?: e.toString(), e.javaClass.simpleName)

    private fun status(space: String, s: MobileTunnelStatus): JSObject {
        val o = JSObject()
            .put("space", space)
            .put("state", s.state.name.lowercase())
            .put("proxyUrl", s.proxyUrl)
            .put("websocketUrl", s.websocketUrl)
            .put("txBytes", s.txBytes.toLong())
            .put("rxBytes", s.rxBytes.toLong())
            .put("connections", s.connections.toLong())
        s.lastHandshakeSecs?.let { o.put("lastHandshakeSecs", it.toLong()) }
        s.error?.let { o.put("error", it) }
        return o
    }

    private fun stop(space: String) {
        tunnels.remove(space)?.let {
            it.stop()
            it.destroy()
        }
    }

    @PluginMethod
    fun startTunnel(call: PluginCall) {
        val space = call.getString("space") ?: return call.reject("space is required", "BadConfig")
        val config = MobileTunnelConfig(
            privateKey = call.getString("privateKey") ?: "",
            peerPublicKey = call.getString("peerPublicKey") ?: "",
            presharedKey = call.getString("presharedKey"),
            endpoint = call.getString("endpoint") ?: "",
            address = call.getString("address") ?: "",
            api = call.getString("api") ?: "",
            keepaliveSecs = call.getInt("keepaliveSecs")?.coerceIn(0, 65535)?.toUShort(),
        )
        // Capacitor calls a plugin off the main thread: resolving the endpoint (DNS) may wait here.
        try {
            stop(space)
            val tunnel = MobileTunnel.start(config)
            tunnels[space] = tunnel
            call.resolve(status(space, tunnel.status()))
        } catch (e: MobileException) {
            reject(call, e)
        }
    }

    @PluginMethod
    fun tunnelStatus(call: PluginCall) {
        val space = call.getString("space") ?: return call.reject("space is required", "BadConfig")
        val tunnel = tunnels[space] ?: return call.reject("no tunnel for this space", "NoTunnel")
        call.resolve(status(space, tunnel.status()))
    }

    @PluginMethod
    fun stopTunnel(call: PluginCall) {
        val space = call.getString("space") ?: return call.reject("space is required", "BadConfig")
        stop(space)
        call.resolve()
    }

    @PluginMethod
    fun openNotification(call: PluginCall) {
        try {
            val n = rustOpenNotification(
                call.getString("pairingKey") ?: "",
                call.getString("sealed") ?: "",
                call.getString("guardState") ?: "",
            )
            val o = JSObject()
                .put("seq", n.seq.toLong())
                .put("at", n.at.toLong())
                .put("kind", n.kind)
                .put("title", n.title)
                .put("body", n.body)
                .put("guardState", n.guardState)
            n.target?.let { o.put("target", it) }
            call.resolve(o)
        } catch (e: MobileException) {
            reject(call, e)
        }
    }

    @PluginMethod
    fun version(call: PluginCall) = call.resolve(JSObject().put("version", mobileVersion()))

    override fun handleOnDestroy() {
        tunnels.keys.toList().forEach(::stop)
        super.handleOnDestroy()
    }
}
