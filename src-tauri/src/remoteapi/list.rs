//! The single list of the app's commands (ESC-478, `docs/REMOTE.md`, « Le classement des commandes »): Tauri's IPC
//! and the remote API are both made from it (`escouade_command::commands!`), so that they never part.
//!
//! **Adding a command**: write it in `commands.rs` with `#[tauri::command]`, as always, then put its name here, in its
//! class:
//! - `served`: it acts on the core, whichever machine the client is on (most commands);
//! - `desk`: the desktop's only (the window and its pages, the tray, the dialogs, the clipboard, the microphone, the
//!   global shortcut, the client's own updater): refused at a distance with the error `desk-only`;
//! - `moves_served` / `moves_refused`: it changes machines in server mode (`docs/REMOTE.md`, « Ce qui change de
//!   machine »): served when it works as it is, else refused with the error `not-served-yet` until the server mode does
//!   it.
//!
//! A command that is not here is not served by the IPC either: `remoteapi_tests` checks every `#[tauri::command]` of the
//! crate is in the list.

